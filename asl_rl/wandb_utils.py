import os
from typing import Any

import wandb

from asl_rl.checkpoint import checkpoint_iteration
from asl_rl.config import PPOConfig


def restore_checkpoint(run_path: str, log_dir: str, filename: str | None = None) -> str:
    """Download a checkpoint from wandb

    Args:
        run_path (str): wandb run identifier, i.e. "entity/project/run_id"
        log_dir (str): Local directory to download into (created if missing).
        filename (str, optional): Specific model_<iter>.pkl to fetch.
            Defaults to None (fetch the highest-numbered checkpoint in the run)

    Returns:
        str: Local path to the downloaded checkpoint
    """
    run = wandb.Api().run(run_path)
    if filename is None:
        ckpts = [
            f
            for f in run.files()
            if f.name.startswith("model_") and f.name.endswith(".pkl")
        ]
        if not ckpts:
            raise FileNotFoundError(f"No model_*.pkl files found in run {run_path}")
        file = max(ckpts, key=lambda f: checkpoint_iteration(f.name))
    else:
        file = run.file(filename)

    os.makedirs(log_dir, exist_ok=True)
    file.download(root=log_dir, replace=True)
    return os.path.join(log_dir, file.name)


class Logger:
    def __init__(
        self,
        project: str,
        cfg: PPOConfig | None = None,
        name: str | None = None,
        run_id: str | None = None,
        **wandb_kwargs: Any,
    ):
        """Thin wandb wrapper for cloud logging

        Args:
            project (str): Wandb project name, e.g. "asl-rl"
            cfg (PPOConfig, optional): Training config. Defaults to None
            name (str, optional): Run name. Defaults to None (autogenerated)
            run_id (str, optional): ID of the run to resume. Defaults to None (new run)
        """
        self.run = wandb.init(
            project=project,
            name=name,
            id=run_id,
            resume="must" if run_id is not None else None,
            config=None if cfg is None else cfg.to_dict(),
            **wandb_kwargs,
        )

    def log(self, data: dict[str, Any], step: int) -> None:
        self.run.log(data, step=step)

    def save(self, path: str) -> None:
        self.run.save(path, base_path=os.path.dirname(path), policy="now")

    def finish(self) -> None:
        self.run.finish()
